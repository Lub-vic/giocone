GRAVE = "01000 00100"
ACUTE = "00010 00100"
ACC = {'À': ('A', GRAVE), 'È': ('E', GRAVE), 'É': ('E', ACUTE), 'Ì': ('I', GRAVE), 'Ò': ('O', GRAVE), 'Ù': ('U', GRAVE)}
LOW = {'à': 'À', 'è': 'È', 'é': 'É', 'ì': 'Ì', 'ò': 'Ò', 'ù': 'Ù'}

CW, CH = 5, 9          # cella glifo: 2 righe per gli accenti + 7 righe
STRIDE_X, STRIDE_Y = 8, 11
COLS = 16


def rows(s):
    return s.split()


def glyph_img(ch):
    im = Image.new("RGBA", (CW, CH), (0, 0, 0, 0))
    px = im.load()
    base = None
    acc = None
    if ch in ACC:
        b, acc = ACC[ch]
        base = rows(G[b])
    elif ch in G:
        base = rows(G[ch])
    if base is None:
        return im
    for y, r in enumerate(base):
        for x, c in enumerate(r):
            if c == '1':
                px[x, y + 2] = (255, 255, 255, 255)
    if acc:
        for y, r in enumerate(acc.split()):
            for x, c in enumerate(r):
                if c == '1':
                    px[x, y] = (255, 255, 255, 255)
    return im


chars = {}
for code in range(32, 127):
    c = chr(code)
    if c.isalpha() and c.islower():
        chars[code] = c.upper()
    else:
        chars[code] = c
for lo, up in LOW.items():
    chars[ord(lo)] = up
for up in ACC:
    chars[ord(up)] = up

codes = sorted(chars)
rows_n = (len(codes) + COLS - 1) // COLS
W, H = COLS * STRIDE_X, rows_n * STRIDE_Y
atlas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
lines = []
for i, code in enumerate(codes):
    cx, cy = (i % COLS) * STRIDE_X, (i // COLS) * STRIDE_Y
    ch = chars[code]
    if ch == ' ':
        lines.append(f"char id={code} x={cx} y={cy} width=1 height=1 xoffset=0 yoffset=0 xadvance=4 page=0 chnl=15")
        continue
    atlas.alpha_composite(glyph_img(ch), (cx, cy))
    adv = 6
    lines.append(f"char id={code} x={cx} y={cy} width={CW} height={CH} xoffset=0 yoffset=0 xadvance={adv} page=0 chnl=15")

atlas.save(os.path.join(OUT, "pixel.png"))
with open(os.path.join(OUT, "pixel.fnt"), "w", encoding="utf8") as f:
    f.write('info face="pixel" size=9 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=0 padding=0,0,0,0 spacing=0,0\n')
    f.write(f"common lineHeight=11 base=9 scaleW={W} scaleH={H} pages=1 packed=0\n")
    f.write('page id=0 file="pixel.png"\n')
    f.write(f"chars count={len(lines)}\n")
    f.write("\n".join(lines) + "\n")
